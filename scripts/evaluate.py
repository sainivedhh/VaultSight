"""Accuracy and benchmark evaluation runner for VaultSight detectors.

Computes:
- Precision, Recall, and F1 per detector
- Overall Precision, Recall, and F1
- False positives and false negatives analysis
- Produces EVALUATION.md with genuine measured metrics
"""

import json
import sys
from pathlib import Path
from collections import defaultdict

# Ensure project root is in sys.path
sys.path.insert(0, str(Path(__file__).parent.parent))

from vaultsight.detectors.engine import DetectionEngine


def evaluate(corpus_path: str = "data/evaluation_corpus.json", output_md: str = "EVALUATION.md"):
    with open(corpus_path, "r", encoding="utf-8") as f:
        corpus = json.load(f)

    engine = DetectionEngine()

    # Per detector stats: TP, FP, FN
    stats = defaultdict(lambda: {"tp": 0, "fp": 0, "fn": 0})
    false_positives = []
    false_negatives = []

    for item in corpus:
        text = item["text"]
        expected_detector = item.get("expected_detector")
        is_positive = item.get("is_positive", False)

        findings = engine.scan_text(text)
        detected_types = list({f.detector for f in findings})

        if is_positive:
            if expected_detector in detected_types:
                stats[expected_detector]["tp"] += 1
                # Check if other unexpected detectors fired
                for dt in detected_types:
                    if dt != expected_detector:
                        stats[dt]["fp"] += 1
                        false_positives.append({
                            "text": text,
                            "expected": expected_detector,
                            "detected": dt,
                            "reason": "Secondary detector falsely triggered on positive sample"
                        })
            else:
                stats[expected_detector]["fn"] += 1
                false_negatives.append({
                    "text": text,
                    "expected": expected_detector,
                    "detected": detected_types,
                    "reason": "Expected detector missed pattern"
                })
        else:
            # Negative sample: should detect nothing
            if detected_types:
                for dt in detected_types:
                    stats[dt]["fp"] += 1
                    false_positives.append({
                        "text": text,
                        "expected": None,
                        "detected": dt,
                        "reason": f"Falsely detected on negative sample ({item.get('negative_type')})"
                    })

    # Compute metrics
    detector_metrics = {}
    total_tp = sum(s["tp"] for s in stats.values())
    total_fp = sum(s["fp"] for s in stats.values())
    total_fn = sum(s["fn"] for s in stats.values())

    for det, s in stats.items():
        tp = s["tp"]
        fp = s["fp"]
        fn = s["fn"]
        precision = tp / (tp + fp) if (tp + fp) > 0 else (1.0 if fn == 0 else 0.0)
        recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
        f1 = (2 * precision * recall) / (precision + recall) if (precision + recall) > 0 else 0.0
        detector_metrics[det] = {
            "tp": tp,
            "fp": fp,
            "fn": fn,
            "precision": round(precision, 4),
            "recall": round(recall, 4),
            "f1": round(f1, 4),
        }

    overall_prec = total_tp / (total_tp + total_fp) if (total_tp + total_fp) > 0 else 0.0
    overall_rec = total_tp / (total_tp + total_fn) if (total_tp + total_fn) > 0 else 0.0
    overall_f1 = (2 * overall_prec * overall_rec) / (overall_prec + overall_rec) if (overall_prec + overall_rec) > 0 else 0.0

    # Generate EVALUATION.md
    md_lines = [
        "# VaultSight: Detection Engine Accuracy Evaluation",
        "",
        "> [!IMPORTANT]",
        "> **Limitations & Benchmark Integrity**: All data is synthetic and generated by `scripts/generate_dataset.py` (fixed random seed = 42). Accuracy numbers reflect this benchmark dataset. Production environments with novel data formats will require continuous tuning.",
        "",
        "## Overall Benchmark Summary",
        f"- **Total Samples Evaluated**: {len(corpus)}",
        f"- **True Positives (TP)**: {total_tp}",
        f"- **False Positives (FP)**: {total_fp}",
        f"- **False Negatives (FN)**: {total_fn}",
        f"- **Overall Precision**: **{overall_prec * 100:.2f}%**",
        f"- **Overall Recall**: **{overall_rec * 100:.2f}%**",
        f"- **Overall F1-Score**: **{overall_f1 * 100:.2f}%**",
        "",
        "## Per-Detector Performance Breakdown",
        "",
        "| Detector ID | True Positives | False Positives | False Negatives | Precision | Recall | F1 Score |",
        "| :--- | :---: | :---: | :---: | :---: | :---: | :---: |",
    ]

    for det, m in sorted(detector_metrics.items()):
        md_lines.append(
            f"| `{det}` | {m['tp']} | {m['fp']} | {m['fn']} | {m['precision']*100:.1f}% | {m['recall']*100:.1f}% | {m['f1']*100:.1f}% |"
        )

    md_lines.extend([
        "",
        "## False Positive & Negative Analysis",
        "",
        f"### False Positives Count: {len(false_positives)}",
    ])

    if false_positives:
        for idx, fp in enumerate(false_positives[:5], 1):
            md_lines.append(f"{idx}. Detected `{fp['detected']}` - Context: `{fp['text'][:70]}...` (Reason: {fp['reason']})")
    else:
        md_lines.append("No false positives observed on this synthetic evaluation run.")

    md_lines.extend([
        "",
        f"### False Negatives Count: {len(false_negatives)}",
    ])

    if false_negatives:
        for idx, fn in enumerate(false_negatives[:5], 1):
            md_lines.append(f"{idx}. Expected `{fn['expected']}` - Context: `{fn['text'][:70]}...` (Reason: {fn['reason']})")
    else:
        md_lines.append("Zero false negatives observed on the labeled positive test set.")

    md_lines.extend([
        "",
        "## Iterations & Tuning Log",
        "1. **Aadhaar Verhoeff Checksum Integration**: Eliminated high rates of false positives on random 12-digit transaction barcodes and shipment tracking IDs.",
        "2. **Indian Mobile Context Weighting**: Un-prefixed 10-digit integers are only flagged when phone/contact keywords exist nearby or start with explicit `+91`/`91` prefixes.",
        "3. **Allowlist / Placeholder Engine**: Placeholders like `AKIAIOSFODNN7EXAMPLE`, `test@example.com`, and `xxxx` are safely excluded from alerts.",
        "4. **Shannon Entropy Minimum Threshold**: Lowered false detections on repetitive strings and simple alphanumeric keys.",
        "",
        "## Remaining Weak Spots & Practical Limits",
        "- **Generic High Entropy Strings**: Unstructured secrets without keyword context (e.g. naked strings in base64 binary files) require careful thresholding to avoid catching compiled bytecode or image chunks.",
        "- **Context Dependency**: Phone numbers without surrounding labels or prefixes cannot be distinguished from random 10-digit IDs with 100% certainty.",
        "- **International Variance**: PII rules are currently optimized for Indian and US identity standards (Aadhaar, PAN, US SSN format patterns). Additional international formats can be configured in `rules.yaml`."
    ])

    with open(output_md, "w", encoding="utf-8") as f:
        f.write("\n".join(md_lines))

    print(f"Evaluation complete. Results written to {output_md}")
    print(f"Overall Metrics -> Precision: {overall_prec*100:.2f}%, Recall: {overall_rec*100:.2f}%, F1: {overall_f1*100:.2f}%")
    return detector_metrics


if __name__ == "__main__":
    evaluate()
